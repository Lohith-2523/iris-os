// Rate limiter states
const RATE_LIMIT_WINDOW = 60 * 1000; // 1 minute
const MAX_REQUESTS = 30; // 30 requests per minute
const requestCounts = new Map<string, number[]>();

function checkRateLimit(key: string): boolean {
  const now = Date.now();
  const timestamps = requestCounts.get(key) || [];
  const activeTimestamps = timestamps.filter(t => now - t < RATE_LIMIT_WINDOW);
  
  if (activeTimestamps.length >= MAX_REQUESTS) {
    return false;
  }
  
  activeTimestamps.push(now);
  requestCounts.set(key, activeTimestamps);
  return true;
}

// Security injection scanning
function detectInjection(query: string): { detected: boolean; reason?: string } {
  if (!query) return { detected: false };
  const q = query.toLowerCase();

  const promptInjectionPatterns = [
    'ignore previous',
    'system prompt',
    'dan mode',
    'you are now offline',
    'bypass',
    'jailbreak',
    'ignore the instructions',
    'forget instructions',
    'new instructions',
    'acting as'
  ];

  for (const pattern of promptInjectionPatterns) {
    if (q.includes(pattern)) {
      return { detected: true, reason: 'Potential prompt injection attempt.' };
    }
  }

  const sqlInjectionPatterns = [
    'union select',
    'drop table',
    'or 1=1',
    'union all select',
    'select * from',
    'delete from',
    'insert into',
    'update pg_',
    'pg_sleep',
    '--'
  ];

  for (const pattern of sqlInjectionPatterns) {
    if (q.includes(pattern)) {
      return { detected: true, reason: 'Potential SQL injection attempt.' };
    }
  }

  return { detected: false };
}

