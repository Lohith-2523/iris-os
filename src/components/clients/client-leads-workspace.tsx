'use client';

import * as React from 'react';
import {
  CheckCircle2,
  Clock3,
  RefreshCw,
  Search,
  UserRoundCheck,
  UsersRound,
} from 'lucide-react';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table';
import { workspaceFetch } from '@/lib/workspace-data-cache';
import { formatUserMessage } from '@/lib/utils';

type MetaLead = {
  id: string;
  leadId: string;
  fullName: string | null;
  email: string | null;
  phone: string | null;
  adName: string | null;
  status: string;
  createdTime: string;
  formId: string | null;
};

const STATUSES = [
  'all',
  'new',
  'cold-call in progress',
  'call back required',
  'closed',
  'unqualified',
] as const;

export function ClientLeadsWorkspace({
  clientName,
  adAccountId,
}: {
  clientName: string;
  adAccountId: string;
}) {
  const [leads, setLeads] = React.useState<MetaLead[]>([]);
  const [loading, setLoading] = React.useState(true);
  const [refreshing, setRefreshing] = React.useState(false);
  const [error, setError] = React.useState('');
  const [query, setQuery] = React.useState('');
  const [status, setStatus] = React.useState<(typeof STATUSES)[number]>('all');
  const [updatingLeadId, setUpdatingLeadId] = React.useState<string | null>(null);

  const loadLeads = React.useCallback(async (refresh = false) => {
    if (refresh) setRefreshing(true);
    else setLoading(true);
    setError('');
    try {
      const response = await workspaceFetch('/api/meta-portal', {
        cache: 'no-store',
      });
      const payload = await response.json();
      if (!response.ok) throw new Error(payload.error || 'Unable to load Meta leads.');
      if (!payload.hasMetaAccount) {
        window.location.replace('/client-dashboard');
        return;
      }
      setLeads(payload.leads || []);
    } catch (loadError) {
      setError(formatUserMessage(
        loadError instanceof Error ? loadError.message : 'Unable to load Meta leads.',
      ));
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  }, []);

  React.useEffect(() => {
    void loadLeads();
  }, [loadLeads]);

  const updateLeadStatus = async (leadId: string, nextStatus: string) => {
    setUpdatingLeadId(leadId);
    setError('');
    try {
      const response = await workspaceFetch('/api/meta-portal', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ leadId, status: nextStatus }),
      });
      const payload = await response.json();
      if (!response.ok) throw new Error(payload.error || 'Unable to update the lead.');
      setLeads((current) =>
        current.map((lead) => lead.leadId === leadId ? { ...lead, status: nextStatus } : lead),
      );
    } catch (updateError) {
      setError(formatUserMessage(
        updateError instanceof Error ? updateError.message : 'Unable to update the lead.',
      ));
    } finally {
      setUpdatingLeadId(null);
    }
  };

  const filteredLeads = React.useMemo(() => {
    const normalizedQuery = query.trim().toLowerCase();
    return leads.filter((lead) => {
      const matchesStatus = status === 'all' || lead.status === status;
      const matchesQuery = !normalizedQuery || [
        lead.fullName,
        lead.email,
        lead.phone,
        lead.adName,
      ].some((value) => value?.toLowerCase().includes(normalizedQuery));
      return matchesStatus && matchesQuery;
    });
  }, [leads, query, status]);

  const closedCount = leads.filter((lead) => lead.status === 'closed').length;
  const followUpCount = leads.filter((lead) =>
    lead.status === 'cold-call in progress' || lead.status === 'call back required',
  ).length;

  if (loading) {
    return (
      <div className="flex h-[60vh] items-center justify-center text-xs text-zinc-500">
        <RefreshCw className="mr-2 h-4 w-4 animate-spin" />
        Loading attributed Meta leads
      </div>
    );
  }

  return (
    <div className="dashboard-canvas space-y-6">
      <div className="dashboard-header flex flex-col gap-4 border-b border-zinc-800/60 pb-5 md:flex-row md:items-end md:justify-between">
        <div>
          <span className="text-[10px] font-bold uppercase tracking-widest text-zinc-500">
            Client workspace
          </span>
          <h1 className="mt-1 text-2xl font-bold tracking-tight text-white">
            Meta Leads
          </h1>
          <p className="mt-1 text-xs text-zinc-500">
            Leads generated by ads attributed to {clientName}.
          </p>
        </div>
        <div className="flex items-center gap-2">
          <Badge variant="outline" className="h-8 border-zinc-800 px-3 font-mono text-[10px] text-zinc-400">
            {adAccountId}
          </Badge>
          <Button
            variant="outline"
            size="sm"
            onClick={() => void loadLeads(true)}
            disabled={refreshing}
            className="h-8 gap-1.5 border-zinc-800 text-zinc-300"
          >
            <RefreshCw className={`h-3.5 w-3.5 ${refreshing ? 'animate-spin' : ''}`} />
            Refresh
          </Button>
        </div>
      </div>

      {error && (
        <div className="rounded-md border border-zinc-700 bg-zinc-900/70 px-4 py-3 text-xs text-zinc-200">
          {error}
        </div>
      )}

      <div className="grid gap-3 md:grid-cols-3">
        {[
          { label: 'Total leads', value: leads.length, icon: UsersRound },
          { label: 'In follow-up', value: followUpCount, icon: Clock3 },
          { label: 'Closed', value: closedCount, icon: CheckCircle2 },
        ].map(({ label, value, icon: Icon }) => (
          <Card key={label}>
            <CardContent className="flex items-center justify-between p-5">
              <div>
                <p className="text-[10px] font-semibold uppercase tracking-wider text-zinc-500">{label}</p>
                <p className="mt-1 font-mono text-2xl font-bold text-white">{value}</p>
              </div>
              <div className="flex h-9 w-9 items-center justify-center rounded-md border border-zinc-800 bg-zinc-900 text-zinc-400">
                <Icon className="h-4 w-4" />
              </div>
            </CardContent>
          </Card>
        ))}
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2 text-sm font-semibold text-white">
            <UserRoundCheck className="h-4 w-4 text-zinc-400" />
            Lead directory
          </CardTitle>
          <CardDescription>
            New Instant Form submissions appear after Meta sends a verified lead notification.
          </CardDescription>
        </CardHeader>
        <CardContent>
          <div className="flex flex-col gap-3 border-b border-zinc-900/60 pb-4 md:flex-row md:items-center md:justify-between">
            <div className="relative max-w-sm flex-1">
              <Search className="absolute left-3 top-2.5 h-3.5 w-3.5 text-zinc-500" />
              <input
                value={query}
                onChange={(event) => setQuery(event.target.value)}
                placeholder="Search name, email, phone, or ad"
                className="w-full rounded-md border border-zinc-800 bg-zinc-900/40 py-2 pl-9 pr-3 text-xs text-white outline-none placeholder:text-zinc-600 focus:border-zinc-700"
              />
            </div>
            <div className="flex flex-wrap gap-1.5">
              {STATUSES.map((item) => (
                <button
                  key={item}
                  type="button"
                  onClick={() => setStatus(item)}
                  className={`rounded border px-2 py-1 text-[9px] font-semibold capitalize transition-colors ${
                    status === item
                      ? 'border-white bg-white text-zinc-950'
                      : 'border-zinc-800 bg-zinc-900/40 text-zinc-400 hover:text-white'
                  }`}
                >
                  {item}
                </button>
              ))}
            </div>
          </div>

          <div className="overflow-x-auto pt-2">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Contact</TableHead>
                  <TableHead>Email</TableHead>
                  <TableHead>Phone</TableHead>
                  <TableHead>Source ad</TableHead>
                  <TableHead>Received</TableHead>
                  <TableHead>Status</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {filteredLeads.length === 0 ? (
                  <TableRow>
                    <TableCell colSpan={6} className="py-12 text-center text-zinc-500">
                      No Meta leads match this view.
                    </TableCell>
                  </TableRow>
                ) : filteredLeads.map((lead) => (
                  <TableRow key={lead.id}>
                    <TableCell className="font-semibold text-white">
                      {lead.fullName || 'Name not provided'}
                    </TableCell>
                    <TableCell className="font-mono text-xs">
                      {lead.email || 'Not provided'}
                    </TableCell>
                    <TableCell className="font-mono text-xs">
                      {lead.phone || 'Not provided'}
                    </TableCell>
                    <TableCell>
                      <span className="block max-w-56 truncate text-xs text-zinc-300">
                        {lead.adName || 'Meta Instant Form'}
                      </span>
                      {lead.formId && (
                        <span className="mt-0.5 block font-mono text-[9px] text-zinc-600">
                          Form {lead.formId}
                        </span>
                      )}
                    </TableCell>
                    <TableCell className="whitespace-nowrap font-mono text-[10px] text-zinc-500">
                      {new Date(lead.createdTime).toLocaleString()}
                    </TableCell>
                    <TableCell>
                      <select
                        value={lead.status}
                        disabled={updatingLeadId === lead.leadId}
                        onChange={(event) => void updateLeadStatus(lead.leadId, event.target.value)}
                        className="rounded border border-zinc-800 bg-zinc-900 px-2 py-1 text-[10px] font-semibold capitalize text-white outline-none"
                      >
                        {STATUSES.filter((item) => item !== 'all').map((item) => (
                          <option key={item} value={item}>{item}</option>
                        ))}
                      </select>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
