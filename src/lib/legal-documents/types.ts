import { z } from 'zod';

const text = (label: string, max = 10_000) => z.string().trim().min(2, `${label} is required`).max(max);
const signatureAudit = z.object({
  recipientName: z.string().trim().max(160).optional(),
  recipientSignedAt: z.string().datetime().optional(),
  agencyName: z.string().trim().max(160).optional(),
  agencySignedAt: z.string().datetime().optional(),
  executedAt: z.string().datetime().optional(),
  contentHash: z.string().trim().max(128).optional(),
}).optional();
const brand = {
  documentNumber: text('Document number', 80),
  title: text('Document title', 180),
  effectiveDate: z.iso.date(),
  agencyName: text('Agency name', 160),
  agencyLegalName: text('Agency legal name', 200),
  agencyEmail: z.email(),
  agencyPhone: z.string().trim().max(40).optional().default(''),
  agencyAddress: text('Agency address', 500),
  clientName: text('Client contact name', 160),
  clientLegalName: text('Client legal name', 200),
  clientEmail: z.email(),
  clientPhone: z.string().trim().max(40).optional().default(''),
  clientAddress: text('Client address', 500),
  brandColor: z.string().regex(/^#[0-9a-fA-F]{6}$/),
  logoDataUrl: z.string().max(5_000_000).optional().default(''),
  signatureAudit,
};

export const contractSchema = z.object({
  kind: z.literal('CONTRACT'),
  ...brand,
  commencementDate: z.iso.date(),
  initialTerm: text('Initial term', 200),
  recitals: text('Background and recitals'),
  services: text('Services'),
  deliverables: text('Deliverables'),
  fees: text('Fees'),
  paymentTerms: text('Payment terms'),
  latePayment: text('Late-payment terms'),
  cancellation: text('Cancellation and refund terms'),
  performanceDisclaimer: text('Performance disclaimer'),
  termination: text('Termination terms'),
  confidentiality: text('Confidentiality terms'),
  publicity: text('Publicity terms'),
  intellectualProperty: text('Intellectual-property terms'),
  dataProtection: text('Data-protection terms'),
  clientObligations: text('Client obligations'),
  agencyObligations: text('Agency obligations'),
  indemnification: text('Indemnification terms'),
  limitationOfLiability: text('Limitation-of-liability terms'),
  independentContractor: text('Independent-contractor terms'),
  assignment: text('Assignment terms'),
  forceMajeure: text('Force-majeure terms'),
  notices: text('Notice terms'),
  amendments: text('Amendment terms'),
  entireAgreement: text('Entire-agreement terms'),
  severability: text('Severability terms'),
  governingLaw: text('Governing law'),
  disputeResolution: text('Dispute-resolution terms'),
  additionalTerms: z.string().trim().max(10_000).optional().default(''),
  agencySignatoryName: text('Agency signatory', 160),
  agencySignatoryTitle: text('Agency signatory title', 120),
  clientSignatoryName: text('Client signatory', 160),
  clientSignatoryTitle: text('Client signatory title', 120),
});

export const sowSchema = z.object({
  kind: z.literal('SOW'),
  ...brand,
  projectName: text('Project name', 180),
  engagementType: text('Engagement type', 140),
  startDate: z.iso.date(),
  endDate: z.iso.date(),
  introduction: text('Introduction'),
  objectives: text('Objectives'),
  scope: text('Scope of work'),
  executionProcess: text('Execution process'),
  deliverables: z.array(z.object({
    name: text('Deliverable name', 180),
    scope: text('Deliverable scope', 600),
    cadence: text('Deliverable cadence', 120),
    acceptance: text('Acceptance criteria', 500),
  })).min(1).max(16),
  milestones: z.array(z.object({
    name: text('Milestone name', 160),
    targetDate: text('Milestone target', 120),
    output: text('Milestone output', 500),
  })).min(1).max(12),
  currency: z.string().trim().min(3).max(8),
  fee: z.coerce.number().min(0),
  taxRate: z.coerce.number().min(0).max(100).default(0),
  pricingNotes: text('Pricing notes'),
  paymentTerms: text('Payment terms'),
  expensesAndAdSpend: text('Expenses and ad-spend terms'),
  revisions: text('Revision terms'),
  reporting: text('Reporting requirements'),
  assumptions: text('Assumptions'),
  dependencies: text('Dependencies'),
  exclusions: text('Exclusions'),
  governance: text('Project governance'),
  changeManagement: text('Change-management process'),
  confidentiality: text('Confidentiality terms'),
  intellectualProperty: text('Intellectual-property terms'),
  termination: text('Termination terms'),
  closingNote: text('Closing note'),
  additionalTerms: z.string().trim().max(10_000).optional().default(''),
  agencySignatoryName: text('Agency signatory', 160),
  agencySignatoryTitle: text('Agency signatory title', 120),
  clientSignatoryName: text('Client signatory', 160),
  clientSignatoryTitle: text('Client signatory title', 120),
});

export const legalDocumentSchema = z.discriminatedUnion('kind', [contractSchema, sowSchema]);
export type ContractInput = z.infer<typeof contractSchema>;
export type SowInput = z.infer<typeof sowSchema>;
export type LegalDocumentInput = z.infer<typeof legalDocumentSchema>;
